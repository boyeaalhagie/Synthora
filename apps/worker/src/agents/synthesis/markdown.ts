import type { Reference, ReportSection, ReportSentence, StudySummary } from "@synthora/schemas";

/** Escapes characters that would otherwise be read as Markdown syntax in table cells. */
const cell = (s: string) => s.replaceAll("|", "\\|").replace(/\s+/g, " ").trim();

function citationMark(sentence: ReportSentence): string {
  return sentence.references.length ? ` [${sentence.references.join(", ")}]` : "";
}

function paragraph(sentences: ReportSentence[]): string {
  return sentences.map((s) => `${s.text}${citationMark(s)}`).join(" ");
}

function studyTable(studies: readonly StudySummary[], refNumber: ReadonlyMap<string, number>): string {
  const header = "| Study | Design | N | Dataset | Methods | Reported metrics |\n|---|---|---|---|---|---|";
  const rows = studies.map((s) => {
    const ref = refNumber.get(s.paperId);
    return `| ${cell(s.label)}${ref ? ` [${ref}]` : ""} | ${cell(s.design?.replaceAll("_", " ") ?? "—")} | ${s.sampleSize?.toLocaleString("en-US") ?? "—"} | ${cell(s.dataset ?? "—")} | ${cell(s.methods.join(", ") || "—")} | ${cell(s.metrics.map((m) => `${m.name}: ${m.value}`).join("; ") || "—")} |`;
  });
  return [header, ...rows].join("\n");
}

export interface MarkdownInput {
  title: string;
  question: string;
  generatedAt: string;
  paperCount: number;
  sections: readonly ReportSection[];
  studies: readonly StudySummary[];
  references: readonly Reference[];
}

/** Renders the verified report as Markdown. Pure: the same report always yields the same document. */
export function renderMarkdown(r: MarkdownInput): string {
  const refNumber = new Map(r.references.map((ref) => [ref.paperId, ref.number]));
  const out: string[] = [
    `# ${r.title}`,
    `**Research question:** ${r.question}`,
    `*Generated by Synthora on ${r.generatedAt.slice(0, 10)} from ${r.paperCount} abstracts. Research support only — not medical advice. Verify findings against the full papers.*`,
  ];

  for (const section of r.sections) {
    out.push(`## ${section.title}`);
    out.push(section.paragraphs.length ? section.paragraphs.map(paragraph).join("\n\n") : "_No statements in this section passed verification._");
    if (section.id === "comparison" && r.studies.length > 0) out.push("### Study characteristics", studyTable(r.studies, refNumber));
  }

  out.push("## References");
  out.push(r.references.length ? r.references.map((ref) => `${ref.number}. ${ref.citation}`).join("\n") : "_No references were cited._");
  return `${out.join("\n\n")}\n`;
}
